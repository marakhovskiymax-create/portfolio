#!/usr/bin/env python3
"""Refresh the static first-screen bundle after editing CSS, locales, i18n.js or entry.js.
No npm build is needed. Run: python tools/sync-first-paint.py
Both editable HTML and dist are updated; image/video bytes are not transformed.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = ("index", "amocrm", "eme-web", "eme-app", "don-ballon", "shable", "eme")
BRAND = {"eme-web": "eme.css", "eme": "eme.css", "eme-app": "eme-app.css", "don-ballon": "don-ballon.css", "shable": "shable.css"}
LOCALES = {lang: json.loads((ROOT / "locales" / f"{lang}.json").read_text()) for lang in ("en", "ru")}
START = "<!-- FIRST-PAINT:START (generated by tools/sync-first-paint.py) -->"
END = "<!-- FIRST-PAINT:END -->"

def css_text(name):
    source = re.sub(r"/\*.*?\*/", " ", (ROOT / name).read_text(), flags=re.S)
    return "\n".join(line.strip() for line in source.splitlines() if line.strip())

def script_text(name):
    source = (ROOT / name).read_text()
    if "</script" in source.lower():
        raise ValueError(f"Unsafe inline script delimiter in {name}")
    return source

for page in PAGES:
    path = ROOT / f"{page}.html"
    html = path.read_text()
    bundle = {}
    for lang, catalog in LOCALES.items():
        messages = {**catalog.get("common", {}), **catalog.get("pages", {}).get(page, {})}
        bundle[lang] = {
            "messages": {key: value for key, value in messages.items() if key != value},
            "meta": catalog.get("meta", {}).get(page, {}),
        }
    catalog_json = json.dumps(bundle, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    sheets = ["styles.css"] + ([] if page == "index" else ["amocrm.css"]) + ([BRAND[page]] if page in BRAND else []) + ["loaders.css", "theme.css", "entry.css", "header-entry.css"]
    block = START + "\n" + "\n".join(f'<style data-inline-source="{name}">\n{css_text(name)}\n</style>' for name in sheets)
    block += f'\n<script id="page-catalog" type="application/json">{catalog_json}</script>\n'
    block += f'<script data-inline-source="i18n.js">\n{script_text("i18n.js")}\n</script>\n'
    block += f'<script data-inline-source="entry.js">\n{script_text("entry.js")}\n</script>\n'
    block += f'<script data-inline-source="header-entry.js">\n{script_text("header-entry.js")}\n</script>\n' + END
    if START in html:
        html = re.sub(re.escape(START) + r"[\s\S]*?" + re.escape(END), lambda _: block, html, count=1)
    else:
        # Replace the old network-gated bootstrap once; later runs only refresh the marked bundle.
        begin = html.index("      // Start only the resources needed for first-screen motion")
        end = html.index("      const fonts = [", begin)
        html = html[:begin] + html[end:]
        html = re.sub(r'\s*<style>\s*html\.locale-pending[\s\S]*?</style>', "", html, count=1)
        html = re.sub(r'\s*<script>\s*document\.documentElement\.classList\.replace\("no-js", "js"\);[\s\S]*?</script>', "", html, count=1)
        html = re.sub(r'\s*<link rel="stylesheet" href="(?:styles|amocrm|eme|eme-app|don-ballon|shable|loaders|theme)\.css[^\"]*"\s*/?>', "", html)
        html = re.sub(r'\s*<script defer src="i18n\.js[^\"]*"[^>]*></script>', "", html)
        marker = '    <script defer src="theme.js'
        at = html.index(marker)
        html = html[:at] + block + "\n" + html[at:]
        # The preview/footer dependencies keep their execution order, but no longer gate Hero.
        marker = '    <script defer src="vendor/ScrollTrigger.min.js"></script>'
        app = '\n    <script defer src="gsap-starter.js"></script>' if page == "index" else ""
        app += '\n    <script defer src="script.js?v=20261125-instant-entry"></script>'
        if page != "index":
            app += '\n    <script defer src="amocrm.js?v=20261125-instant-entry"></script>'
        html = html.replace(marker, marker + app, 1)
        html = html.replace("    </header>", '    </header>\n    <script data-entry-header>window.siteI18n?.apply(document.querySelector(".site-header"));</script>', 1)
        if page == "index":
            start = html.index('<section class="hero"')
            end = html.index("</section>", start) + len("</section>")
            html = html[:end] + '\n      <script data-entry-reveal>window.siteEntry?.reveal(document.querySelector(".hero"));</script>' + html[end:]
        else:
            at = html.index('        <div class="case-carousel')
            html = html[:at] + '        <script data-entry-reveal>window.siteEntry?.reveal(document.querySelector(".case-hero__copy"));</script>\n' + html[at:]
        html = html.replace("  </body>", '    <script data-entry-complete>window.siteI18n?.start();</script>\n  </body>', 1)
    # Prime/restore before the deferred GSAP reference scripts execute. Request
    # motion dependencies first so analytics/theme helpers cannot delay entrances.
    html = html.replace('window.siteI18n?.apply(document.querySelector(".site-header"));</script>', 'window.siteI18n?.apply(document.querySelector(".site-header"));window.siteEntry?.resume();</script>')
    html = html.replace('window.siteI18n?.start();</script>', 'window.siteI18n?.start();window.siteEntry?.complete();</script>')
    pattern = r'\s*<script defer(?: [^>]*)? src="(?:vendor/(?:gsap|ScrollTrigger)\.min\.js|gsap-starter\.js|script\.js[^\"]*|amocrm\.js[^\"]*)"[^>]*></script>'
    html = re.sub(pattern, "", html)
    sources = ["vendor/gsap.min.js", "vendor/ScrollTrigger.min.js"]
    if page == "index":
        sources.append("gsap-starter.js")
    sources.append("script.js?v=20261127-language-hover-exit")
    if page != "index":
        sources.append("amocrm.js?v=20261126-gallery-results")
    failed = 'window.siteCriticalScriptFailed=true;window.siteEntry?.release();'
    tags = "\n".join(f'<script defer src="{name}" onerror="{failed}"></script>' for name in sources)
    html = html.replace(START, tags + "\n" + START, 1)
    assert "locale-pending" not in re.sub(r'<style[^>]*>[\s\S]*?</style>|<script[^>]*>[\s\S]*?</script>', "", html)
    path.write_text(html)
    shutil.copy2(path, ROOT / "dist" / path.name)

for name in ("i18n.js", "entry.js", "entry.css", "header-entry.js", "header-entry.css", "script.js", "amocrm.js", "styles.css", "amocrm.css", "loaders.css", "theme.js", "theme.css", "eme.css", "eme-app.css", "don-ballon.css", "shable.css"):
    shutil.copy2(ROOT / name, ROOT / "dist" / name)
print(f"Updated {len(PAGES)} static pages and source/dist scripts. No network requests or publishing performed.")
